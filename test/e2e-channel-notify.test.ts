import { describe, it, expect, beforeAll, afterAll } from "vitest";
import { WebSocket } from "ws";

// Test configuration
const DAEMON_WS = process.env.GENTLE_DOT_URL || "ws://localhost:4317/ws";
const DAEMON_TOKEN_FILE = process.env.GENTLE_DOT_TOKEN_FILE || "/home/dot/.gentle-dot/token";
const BRIDGE_ADMIN_URL = process.env.DOT_WHATSAPP_ADMIN_URL || "http://localhost:4407";
const ADMIN_TOKEN = process.env.DOT_WHATSAPP_ADMIN_TOKEN || "test-admin-token-0123456789abcdef";
const TEST_NUMBER = "5491112345678";

let ws: WebSocket;
let daemonToken: string;
let seq = 0;

async function readToken(): Promise<string> {
    // In E2E, token is generated by gentle-dot entrypoint
    try {
        const fs = await import("node:fs");
        return fs.readFileSync(DAEMON_TOKEN_FILE, "utf8").trim();
    } catch {
        return "test-token"; // fallback for test
    }
}

function send(payload: object): Promise<object> {
    return new Promise((resolve, reject) => {
        const msg = JSON.stringify({ ...payload, seq: ++seq });
        ws.send(msg);
        
        const timeout = setTimeout(() => reject(new Error("Timeout")), 5000);
        
        ws.once("message", (data) => {
            clearTimeout(timeout);
            try {
                resolve(JSON.parse(data.toString()));
            } catch {
                resolve({ raw: data.toString() });
            }
        });
    });
}

async function connectDaemon(): Promise<void> {
    daemonToken = await readToken();
    
    ws = new WebSocket(DAEMON_WS);
    
    await new Promise<void>((resolve, reject) => {
        ws.on("open", () => {
            ws.send(JSON.stringify({
                type: "hello",
                token: daemonToken,
                protocol: 1
            }));
        });
        
        ws.on("message", (data) => {
            const msg = JSON.parse(data.toString());
            if (msg.type === "ready") {
                resolve();
            }
        });
        
        ws.on("error", reject);
        ws.on("close", () => reject(new Error("WS closed")));
        
        setTimeout(() => reject(new Error("Connection timeout")), 10000);
    });
}

async function adminCall(method: string, path: string, body?: object): Promise<any> {
    const response = await fetch(`${BRIDGE_ADMIN_URL}${path}`, {
        method,
        headers: {
            "authorization": `Bearer ${ADMIN_TOKEN}`,
            "content-type": "application/json",
        },
        body: body ? JSON.stringify(body) : undefined,
    });
    
    if (!response.ok) {
        const text = await response.text();
        throw new Error(`Admin API ${method} ${path} failed: ${response.status} ${text}`);
    }
    
    return response.json();
}

describe("E2E: channel_notify flow (P0-1)", () => {
    beforeAll(async () => {
        await connectDaemon();
    }, 30000);

    afterAll(() => {
        ws?.close();
    });

    it("daemon is reachable and bridge is connected", async () => {
        const status = await adminCall("GET", "/status");
        expect(status.provider).toBe("baileys");
        expect(status.reachable).toBe(true);
    });

    it("allowlist contains test number", async () => {
        const numbers = await adminCall("GET", "/allowlist");
        expect(numbers).toContain("…5678"); // masked
    });

    it("sends channel_notify via daemon WS and bridge delivers", async () => {
        const testText = `🔔 E2E test ${Date.now()}`;
        
        // Send channel_notify via daemon WS (simulating assistant)
        const notifyPayload = {
            type: "channel_notify",
            to: TEST_NUMBER,
            text: testText,
            requestId: `e2e-${Date.now()}`
        };
        
        await send(notifyPayload);
        
        // Wait a bit for bridge to process
        await new Promise(r => setTimeout(r, 1000));
        
        // Verify bridge received it by checking Engram or bridge logs
        // In a real test, we'd check the bridge's sent messages
        // For now, verify the daemon accepted it
        expect(true).toBe(true); // placeholder - actual verification needs bridge instrumentation
    });

    it("bridge rejects channel_notify for non-allowlisted number", async () => {
        const notifyPayload = {
            type: "channel_notify",
            to: "11000000000", // not in allowlist
            text: "should be rejected",
            requestId: `e2e-reject-${Date.now()}`
        };
        
        await send(notifyPayload);
        
        // The bridge should log rejection but not crash
        await new Promise(r => setTimeout(r, 500));
        expect(true).toBe(true);
    });

    it("bridge handles channel_notify with missing fields gracefully", async () => {
        const notifyPayload = {
            type: "channel_notify",
            to: "",
            text: "missing to",
        };
        
        await send(notifyPayload);
        await new Promise(r => setTimeout(r, 500));
        
        const notifyPayload2 = {
            type: "channel_notify",
            to: TEST_NUMBER,
            text: "",
        };
        
        await send(notifyPayload2);
        await new Promise(r => setTimeout(r, 500));
        
        expect(true).toBe(true);
    });

    it("idempotency: duplicate requestId is not delivered twice", async () => {
        const requestId = `e2e-idempotent-${Date.now()}`;
        const testText = `Idempotent test ${requestId}`;
        
        // First send
        await send({
            type: "channel_notify",
            to: TEST_NUMBER,
            text: testText,
            requestId
        });
        
        // Second send with same requestId
        await send({
            type: "channel_notify",
            to: TEST_NUMBER,
            text: "should be ignored",
            requestId
        });
        
        await new Promise(r => setTimeout(r, 1000));
        expect(true).toBe(true);
    });
});

describe("E2E: bridge admin API", () => {
    it("pair status endpoint works", async () => {
        const status = await adminCall("GET", "/pair/status");
        // Should be null when not pairing
        expect(status).toBeNull();
    });

    it("verify endpoint sends test message", async () => {
        const results = await adminCall("POST", "/verify");
        expect(Array.isArray(results)).toBe(true);
        expect(results.length).toBeGreaterThan(0);
        expect(results[0]).toHaveProperty("masked");
        expect(results[0]).toHaveProperty("ok");
    });
});